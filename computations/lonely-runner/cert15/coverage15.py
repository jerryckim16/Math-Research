"""Build results/COVERAGE.md and results/summary.json from results/gate_<p>.json
(LRC(15) gate certificates of Allikvere, Zenodo 10.5281/zenodo.23304361).

Usage: python3 -I coverage15.py
"""
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
GATES = [p for p in range(269, 660) if all(p % q for q in range(2, int(p ** 0.5) + 1))
         and p not in (271, 277, 283, 293, 307)]
assert len(GATES) == 59


def main():
    rows, done, passed, per_gate = [], [], [], []
    tot = {"ir_rows": 0, "ext_rows": 0, "cascade_rows": 0, "survivor_rows": 0, "seconds": 0.0}
    for p in GATES:
        f = os.path.join(RES, "gate_%d.json" % p)
        if not os.path.exists(f):
            rows.append("| %d | not run | | | | | | | | |" % p)
            continue
        r = json.load(open(f))
        done.append(p)
        if r["pass"]:
            passed.append(p)
        ct = r["cascade_totals_ours"]
        died = ", ".join("%s: %d" % (k[5:], v) for k, v in sorted(ct.items(), key=lambda kv: int(kv[0][6:]) if kv[0].startswith("died_l") else 0)
                         if k.startswith("died_l"))
        ext = r["cascade_rows"] - r["ir_rows"]
        per_gate.append({"p": p, "pass": r["pass"], "sha256": r["sha256"], "ir_rows": r["ir_rows"],
                         "km1_rooted": r["km1_rooted"], "km1_dedup": r["km1_dedup"], "ext_rows": ext,
                         "level2_survivors": ct["survivor_rows"],
                         "died": {k[5:]: v for k, v in ct.items() if k.startswith("died_l")},
                         "trace16": r["rows_first_empty_at_16_trace"], "seconds": r["seconds"]})
        tot["ir_rows"] += r["ir_rows"]
        tot["ext_rows"] += ext
        tot["cascade_rows"] += r["cascade_rows"]
        tot["survivor_rows"] += ct["survivor_rows"]
        tot["seconds"] += r["seconds"]
        rows.append("| %d | %s | %s | %d | %d / %d | %d | %d | %s | %s | %s |" % (
            p, "ok" if r["sha256_ok"] else "FAIL",
            "ok (%d)" % r["manifest_entries"] if r["manifest_mismatch"] == 0 else "FAIL",
            r["ir_rows"], r["km1_rooted"], r["km1_dedup"], ext, ct["survivor_rows"], died,
            "/".join(map(str, r["rows_first_empty_at_16_trace"][0])) if r["rows_first_empty_at_16_trace"] else "-",
            "**pass**" if r["pass"] else "**FAIL**: " + "; ".join(m["what"] for m in r["mismatches"])))
    s = sum(math.log(p) for p in passed)
    out = ["# LRC(15) gate certificates: coverage of our re-check",
           "",
           "Generated by `coverage15.py` from `gate_<p>.json` (written by `check_gate15.py` via `run_all15.py`).",
           "Source: J. Allikvere, *Sixteen lonely runners*, Zenodo 10.5281/zenodo.23304361; 59 gates, all primes 269..659 "
           "except 271, 277, 283, 293, 307.",
           "",
           "Columns: archive SHA-256 vs his SHA256SUMS.txt; internal MANIFEST_SHA256.json (entries); stored irredundant rows; "
           "rooted / deduplicated 14-class covers; extension rows (dedup cover + every class); rows with an improper level-2 lift; "
           "level at which those fibres first become empty (count); improper-fibre trace l2/l4/l8/l16 of the rows that die at 16; result.",
           "",
           "Every check marked pass covers **every** stored row (no sampling). **Not checked at any gate here:** level-one "
           "completeness (that the stored rows represent every unit orbit of I(15,p,1)), including the covering-number "
           "precondition tau(p) >= 14.",
           "",
           "| p | archive | manifest | ir rows | km1 rooted / dedup | ext rows | level-2 survivors | first empty at | trace of rows dying at 16 | result |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"] + rows + [
           "",
           "Gates run: %d of 59; passed: %d. Rows re-checked: %d irredundant + %d extension = %d; level-2 survivors %d. "
           "Wall time %.0f s (1 process). Sum of log p over passed gates: %.8f." % (
               len(done), len(passed), tot["ir_rows"], tot["ext_rows"], tot["cascade_rows"], tot["survivor_rows"],
               tot["seconds"], s)]
    open(os.path.join(RES, "COVERAGE.md"), "w").write("\n".join(out) + "\n")
    json.dump({"gates_run": done, "gates_passed": passed, "totals": tot, "sum_log_p_passed": s, "per_gate": per_gate},
              open(os.path.join(RES, "summary.json"), "w"), indent=1)
    print(len(done), len(passed), tot)


if __name__ == "__main__":
    main()
